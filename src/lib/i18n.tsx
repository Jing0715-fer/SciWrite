/**
 * Resolve a locale string safely — falls back to en-US if the runtime
 * does not support the requested locale.
 */
function safeLocale(lang: Lang): string {
  const loc = langLocales[lang];
  try {
    // Probe: if Intl.DateTimeFormat throws, fall back.
    Intl.DateTimeFormat.supportedLocalesOf(loc);
    return loc;
  } catch {
    return "en-US";
  }
}

/**
 * Format a date in the user's locale.
 * Accepts Date | ISO string | epoch ms.
 */
export function formatDateForLang(
  date: Date | string | number,
  lang: Lang,
  opts?: Intl.DateTimeFormatOptions
): string {
  const d = typeof date === "string" || typeof date === "number" ? new Date(date) : date;
  if (isNaN(d.getTime())) return "—";
  try {
    return new Intl.DateTimeFormat(safeLocale(lang), {
      year: "numeric",
      month: "short",
      day: "numeric",
      ...opts,
    }).format(d);
  } catch {
    return d.toISOString().slice(0, 10);
  }
}

/**
 * Format a number in the user's locale (grouping separators, decimals).
 */
export function formatNumberForLang(
  n: number,
  lang: Lang,
  opts?: Intl.NumberFormatOptions
): string {
  try {
    return new Intl.NumberFormat(safeLocale(lang), opts).format(n);
  } catch {
    return String(n);
  }
}

/**
 * Format a date as a relative time string (e.g. "3 days ago", "2時間前").
 * Uses Intl.RelativeTimeFormat when available.
 */
export function formatRelativeForLang(
  date: Date | string | number,
  lang: Lang
): string {
  const d = typeof date === "string" || typeof date === "number" ? new Date(date) : date;
  if (isNaN(d.getTime())) return "—";
  const diffMs = d.getTime() - Date.now();
  const sec = Math.round(diffMs / 1000);
  const absSec = Math.abs(sec);
  const loc = safeLocale(lang);
  try {
    const rtf = new Intl.RelativeTimeFormat(loc, { numeric: "auto" });
    if (absSec < 60) return rtf.format(sec, "second");
    const min = Math.round(sec / 60);
    if (Math.abs(min) < 60) return rtf.format(min, "minute");
    const hr = Math.round(sec / 3600);
    if (Math.abs(hr) < 24) return rtf.format(hr, "hour");
    const day = Math.round(sec / 86400);
    if (Math.abs(day) < 30) return rtf.format(day, "day");
    const month = Math.round(sec / 2592000);
    if (Math.abs(month) < 12) return rtf.format(month, "month");
    const year = Math.round(sec / 31536000);
    return rtf.format(year, "year");
  } catch {
    return formatDateForLang(d, lang);
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("en");

  React.useEffect(() => {
    try {
      const saved = localStorage.getItem("sciwrite-lang") as Lang | null;
      if (saved && saved in langNativeNames) {
        setLangState(saved);
      }
    } catch {}
  }, []);

  // Keep <html lang> in sync so language-sensitive CSS (:lang(zh) typography
  // polish in globals.css), screen readers, and browser translation hints
  // all reflect the active language.
  React.useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = React.useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("sciwrite-lang", l);
    } catch {}
  }, []);

  const t = React.useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      // Look up in the current language first, then fall back to English,
      // then to the key itself. This lets partial translations (ja/ko/fr)
      // coexist with the complete en/zh dictionaries.
      const dict = translations[lang] as Record<string, string>;
      const enDict = translations.en as Record<string, string>;
      const raw = dict[key] || enDict[key] || key;
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
        vars[name] !== undefined ? String(vars[name]) : `{${name}}`
      );
    },
    [lang]
  );

  const formatDate = React.useCallback(
    (date: Date | string | number, opts?: Intl.DateTimeFormatOptions) =>
      formatDateForLang(date, lang, opts),
    [lang]
  );

  const formatNumber = React.useCallback(
    (n: number, opts?: Intl.NumberFormatOptions) =>
      formatNumberForLang(n, lang, opts),
    [lang]
  );

  const formatRelative = React.useCallback(
    (date: Date | string | number) => formatRelativeForLang(date, lang),
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t, formatDate, formatNumber, formatRelative }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return React.useContext(I18nContext);
}
